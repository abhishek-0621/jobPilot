    SOURCE_TIMEOUT = "SOURCE_TIMEOUT"
    SOURCE_RATE_LIMIT = "SOURCE_RATE_LIMIT"
    SOURCE_CHANGED = "SOURCE_CHANGED"
    SOURCE_UNAVAILABLE = "SOURCE_UNAVAILABLE"
    MODEL_UNAVAILABLE = "MODEL_UNAVAILABLE"
